// simple java program that prints out different operations and concatenations

public class EX13{
    public static void main(String[] args){
	    int x = 5;
	    int y = 3;
	    //first operation prints out the addition of two integers
	    System.out.println(x+y);
	    //second operation prints out the two integer addition, converts it to a string and then concatenates it with !
	    System.out.println(x + y + "!");
	    //third operation prints the string then converts the ints to strings and concatenates all strings
	    System.out.println("printing: " + x + y);
	    //fourth operation performs integer multiplication, converts the multiplication to string and then concatenates with string
	    System.out.println("printing: " + x * y);
    }
}
